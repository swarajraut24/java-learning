package com.tca ;

public class Student {
  
	private int rno ;
	private String name;
	private int per;
	 
	
	public void setRno(int rno) {
		this.rno = rno;
	}

	public void setName(String name) {
		this.name = name;
	}

	public void setPer(int per) {
		this.per = per;
	}

	public int getRno() {
		return rno;
	}
	
	public String getName() {
		return name;
	}
	
	public int getPer() {
		return per;
	}
}