import java.io.*;
import java.util.*;
public class hashset{

	public static void main(String args[])  {

    
    //hashset:-

     HashSet<String> hs=new HashSet<>();

     hs.add("pune");
     hs.add("goa");
     hs.add("barshi");
     hs.add("delhi");

     System.out.println(hs);

     //linkedlist:-

     LinkedList<String> ht=new LinkedList<>();

     ht.add("pune");
     ht.add("goa");
     ht.add("barshi");
     ht.add("delhi");
     
     System.out.println(ht);

}
}